def main():
    parser = argparse.ArgumentParser(description="Generate the synthetic NBFC lending demo database.")
    parser.add_argument("--scale", choices=list(SCALE_PRESETS.keys()), default="full")
    parser.add_argument("--db-url", default=os.getenv("LENDING_DATABASE_URL", "postgresql://saarthi:password@localhost:5432/postgres"))
    parser.add_argument("--db-name", default="lending_demo_db")
    args = parser.parse_args()

    preset = SCALE_PRESETS[args.scale]
    log(f"Scale='{args.scale}' preset={preset}")

    ensure_database(args.db_url, args.db_name)
    target_url = derive_db_url(args.db_url, args.db_name)
    conn = psycopg2.connect(target_url)
    conn.autocommit = False

    t0 = time.time()
    with conn.cursor() as cur:
        log("Creating schema...")
        cur.execute(SCHEMA_SQL)
    conn.commit()

    branches = generate_branches(preset["branches"], conn)
    employee_ids_by_branch = generate_employees(preset["employees_per_branch"], branches, conn)
    agent_ids_by_branch = generate_agents(preset["agents"], branches, conn)
    products = generate_loan_products(conn)
    customers = generate_customers(preset["customers"], branches, conn)

    loans = generate_applications_and_loans(
        customers, products, employee_ids_by_branch, agent_ids_by_branch,
        preset["apps_per_customer"], conn,
    )

    loan_final_dpd, loan_npa_flag = simulate_and_write_schedule_collections(
        loans, employee_ids_by_branch, agent_ids_by_branch, conn,
    )
    backfill_loan_dpd_and_npa(loan_final_dpd, loan_npa_flag, conn)
    generate_npa_classification(loans, loan_final_dpd, conn)
    generate_credit_bureau_records(customers, conn)
    generate_payables(loans, branches, agent_ids_by_branch, conn)
    generate_ledger(loans, conn)

    log("Creating indexes...")
    with conn.cursor() as cur:
        cur.execute(INDEX_SQL)
    conn.commit()

    with conn.cursor() as cur:
        cur.execute("SELECT pg_size_pretty(pg_database_size(%s))", (args.db_name,))
        size = cur.fetchone()[0]

    elapsed = time.time() - t0
    log(f"Done in {elapsed:.1f}s. Database '{args.db_name}' size: {size}")
    conn.close()


if __name__ == "__main__":
    main()
