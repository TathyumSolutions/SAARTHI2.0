def gen_pan() -> str:
    letters1 = "".join(random.choices("ABCDEFGHIJKLMNOPQRSTUVWXYZ", k=5))
    digits = "".join(random.choices("0123456789", k=4))
    letter2 = random.choice("ABCDEFGHIJKLMNOPQRSTUVWXYZ")
    return f"{letters1}{digits}{letter2}"


def gen_aadhaar_masked() -> str:
    last4 = "".join(random.choices("0123456789", k=4))
    return f"XXXX-XXXX-{last4}"


def gen_mobile() -> str:
    first = random.choice("6789")
    rest = "".join(random.choices("0123456789", k=9))
    return f"+91{first}{rest}"


def gen_ifsc(bank_name: str) -> str:
    prefix = "".join(ch for ch in bank_name.upper() if ch.isalpha())[:4].ljust(4, "X")
    return f"{prefix}0{random.randint(100000, 999999):06d}"[:11]


def weighted_choice(pairs):
    values, weights = zip(*pairs)
    return random.choices(values, weights=weights, k=1)[0]


def emi_amount(principal: float, annual_rate: float, tenure_months: int) -> float:
    r = annual_rate / 12 / 100
    if r == 0:
        return round(principal / tenure_months, 2)
    factor = (1 + r) ** tenure_months
    return round(principal * r * factor / (factor - 1), 2)


def random_date(start: date, end: date) -> date:
    delta_days = (end - start).days
    if delta_days <= 0:
        return start
    return start + timedelta(days=random.randint(0, delta_days))


