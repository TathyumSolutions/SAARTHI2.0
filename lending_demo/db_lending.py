# Risk profile mix drives repayment behaviour downstream.
RISK_PROFILES = [("Good", 0.68), ("Average", 0.22), ("Risky", 0.10)]
APP_STATUS_WEIGHTS_BY_CIBIL_BAND = {
    # (approved, rejected, withdrawn) — better CIBIL -> higher approval odds
    "high": (0.90, 0.06, 0.04),
    "mid": (0.72, 0.20, 0.08),
    "low": (0.38, 0.52, 0.10),
}
REJECTION_REASONS = [
    "Low CIBIL score", "Income to obligation ratio too high", "Incomplete KYC documents",
    "Negative credit bureau remarks", "Unable to verify address", "Existing overdue loan",
    "Employer not in approved list", "Applicant below minimum vintage",
]


def cibil_band(score: int) -> str:
    if score >= 720:
        return "high"
    if score >= 650:
        return "mid"
    return "low"


@dataclass
class LoanApp:
    application_id: int
    customer: Customer
    product: dict
    branch_id: int
    status: str
    applied_date: date
    amount: float
    tenure: int


def generate_applications_and_loans(
    customers: list[Customer], products: list[dict],
    employee_ids_by_branch: dict, agent_ids_by_branch: dict,
    apps_per_customer: float, conn,
):
    app_writer = CopyWriter(conn, "loan_applications", [
        "application_id", "application_number", "customer_id", "product_id", "branch_id",
        "agent_id", "credit_analyst_id", "applied_date", "requested_amount",
        "requested_tenure_months", "status", "rejection_reason", "decision_date",
    ])
    loan_writer = CopyWriter(conn, "loans", [
        "loan_id", "loan_account_number", "application_id", "customer_id", "product_id",
        "branch_id", "sanctioned_amount", "disbursed_amount", "interest_rate", "tenure_months",
        "emi_amount", "disbursement_date", "first_emi_date", "maturity_date",
        "disbursing_bank", "loan_status", "closure_date", "risk_profile", "current_dpd", "npa_flag",
    ], depends_on=[app_writer])

    approved_loans: list[dict] = []
    app_id = 0
    loan_id = 0
    today = date(2026, 8, 22)

    for cust in customers:
        n_apps = np.random.poisson(apps_per_customer) or 1
        for _ in range(n_apps):
            app_id += 1
            product = random.choice(products)
            band = cibil_band(cust.cibil)
            approved_p, rejected_p, withdrawn_p = APP_STATUS_WEIGHTS_BY_CIBIL_BAND[band]

            lo, hi = product["min_amount"], min(product["max_amount"], cust.income * 30)
            hi = max(hi, lo * 1.05)
            amount = round(random.uniform(lo, hi), -3) or lo
            tenure = random.randint(product["min_tenure"], product["max_tenure"])
            applied = random_date(date(2019, 1, 1), today - timedelta(days=1))

            status = weighted_choice([
                ("Approved", approved_p), ("Rejected", rejected_p), ("Withdrawn", withdrawn_p),
            ])
            branch_id = cust.branch_id
            agent_pool = agent_ids_by_branch.get(branch_id) or []
            agent_id = random.choice(agent_pool) if agent_pool and random.random() < 0.55 else None
            analyst_pool = employee_ids_by_branch.get(branch_id) or []
            analyst_id = random.choice(analyst_pool) if analyst_pool else None
            decision_date = applied + timedelta(days=random.randint(1, 21))
            rejection_reason = random.choice(REJECTION_REASONS) if status == "Rejected" else None

            app_writer.add((
                app_id, f"APP{app_id:08d}", cust.customer_id, product["product_id"], branch_id,
                agent_id, analyst_id, applied, amount, tenure, status, rejection_reason,
                decision_date if status != "Submitted" else None,
            ))

            if status != "Approved":
                continue

            # A fraction of approvals never get disbursed (customer backed out).
            if random.random() < 0.04:
                continue

            loan_id += 1
            rate = round(random.uniform(product["rate_min"], product["rate_max"]), 2)
            disbursement_date = decision_date + timedelta(days=random.randint(1, 10))
            if disbursement_date >= today:
                continue
            first_emi = (disbursement_date.replace(day=1) + timedelta(days=32)).replace(day=min(disbursement_date.day, 28))
            emi = emi_amount(amount, rate, tenure)
            maturity = first_emi + timedelta(days=30 * tenure)
            risk_profile = weighted_choice(RISK_PROFILES)

            months_elapsed = max(0, (today.year - disbursement_date.year) * 12 + (today.month - disbursement_date.month))
            closed_naturally = months_elapsed >= tenure and random.random() < 0.97
            foreclosed = (not closed_naturally) and months_elapsed >= 6 and random.random() < 0.06
            loan_status = "Closed" if closed_naturally else ("Foreclosed" if foreclosed else "Active")
            closure_date = None
            if loan_status in ("Closed", "Foreclosed"):
                closure_date = min(maturity, disbursement_date + timedelta(days=30 * min(tenure, months_elapsed)))

            loan = dict(
                loan_id=loan_id, application_id=app_id, customer=cust, product=product,
                branch_id=branch_id, sanctioned_amount=amount, interest_rate=rate,
                tenure_months=tenure, emi_amount=emi, disbursement_date=disbursement_date,
                first_emi_date=first_emi, maturity_date=maturity, loan_status=loan_status,
                closure_date=closure_date, risk_profile=risk_profile,
                months_elapsed=min(months_elapsed, tenure),
            )
            approved_loans.append(loan)

            loan_writer.add((
                loan_id, f"LN{loan_id:09d}", app_id, cust.customer_id, product["product_id"],
                branch_id, amount, amount, rate, tenure, emi, disbursement_date, first_emi,
                maturity, random.choice(BANK_NAMES), loan_status, closure_date, risk_profile,
                0, False,  # current_dpd / npa_flag finalized after schedule simulation (UPDATE pass)
            ))

    app_writer.flush()
    loan_writer.flush()
    log(f"loan_applications: {app_writer.total} rows")
    log(f"loans: {loan_writer.total} rows")
    return approved_loans


# Repayment behaviour is modelled as a 2-state Markov chain per loan
# ("current" <-> "delinquent") rather than independent-per-month coin
# flips: real delinquency is sticky (a borrower who falls behind tends to
# stay behind for a few months, not bounce back and forth randomly), and
# that stickiness is what actually produces 90+ DPD NPAs. p_default is the
# monthly hazard of a current loan slipping into delinquency; p_cure is the
# monthly chance a delinquent loan fully catches up and returns to current.
DELINQUENCY_PARAMS = {
    "Good":    dict(p_default=0.005, p_cure=0.55, late_given_current=0.06),
    "Average": dict(p_default=0.024, p_cure=0.35, late_given_current=0.16),
    "Risky":   dict(p_default=0.070, p_cure=0.17, late_given_current=0.30),
}


def simulate_and_write_schedule_collections(
    loans: list[dict], employee_ids_by_branch: dict, agent_ids_by_branch: dict, conn,
):
    sched_writer = CopyWriter(conn, "repayment_schedule", [
        "schedule_id", "loan_id", "installment_number", "due_date", "opening_principal",
        "principal_due", "interest_due", "emi_due", "closing_principal", "amount_paid",
        "paid_date", "payment_status", "dpd_days",
    ])
    coll_writer = CopyWriter(conn, "collections", [
        "collection_id", "receipt_number", "loan_id", "schedule_id", "customer_id",
        "collection_date", "principal_component", "interest_component", "penalty_component",
        "total_amount", "payment_mode", "collected_by_employee_id", "collected_by_agent_id",
    ], depends_on=[sched_writer])

    schedule_id = 0
    collection_id = 0
    loan_final_dpd: dict[int, int] = {}
    loan_npa_flag: dict[int, bool] = {}
    today = date(2026, 8, 22)

    for loan in loans:
        params = DELINQUENCY_PARAMS[loan["risk_profile"]]
        principal_remaining = float(loan["sanctioned_amount"])
        monthly_rate = loan["interest_rate"] / 12 / 100
        due_date = loan["first_emi_date"]
        emi = float(loan["emi_amount"])
        installments_to_simulate = loan["months_elapsed"] if loan["loan_status"] != "Active" else \
            min(loan["tenure_months"], max(1, (today.year - loan["disbursement_date"].year) * 12 +
                                            (today.month - loan["disbursement_date"].month)))
        simulated_installments: list[tuple[date, str]] = []  # (due_date, status) in order
        delinquent = False

        for inst_no in range(1, loan["tenure_months"] + 1):
            interest_due = round(principal_remaining * monthly_rate, 2)
            principal_due = round(min(emi - interest_due, principal_remaining), 2)
            if principal_due < 0:
                principal_due = 0
            emi_due = round(principal_due + interest_due, 2)
            closing_principal = round(max(principal_remaining - principal_due, 0), 2)

            schedule_id += 1
            this_sched_id = schedule_id

            if inst_no <= installments_to_simulate:
                just_defaulted = False
                if not delinquent and random.random() < params["p_default"]:
                    delinquent = True
                    just_defaulted = True

                if not delinquent:
                    if random.random() < params["late_given_current"]:
                        delay = random.randint(1, 20)
                        paid_date = due_date + timedelta(days=delay)
                        dpd = delay
                    else:
                        paid_date = due_date - timedelta(days=random.randint(0, 3))
                        dpd = 0
                    amount_paid = emi_due
                    status = "Paid"
                elif (not just_defaulted) and random.random() < params["p_cure"]:
                    # Catches up in full this month (collections applies
                    # the payment to clear the arrears too).
                    delinquent = False
                    paid_date = due_date + timedelta(days=random.randint(5, 25))
                    amount_paid = emi_due
                    status = "Paid"
                    dpd = (today - due_date).days if due_date < today else 0
                elif random.random() < 0.30:
                    paid_date = due_date + timedelta(days=random.randint(0, 20))
                    amount_paid = round(emi_due * random.uniform(0.3, 0.8), 2)
                    status = "Partially Paid"
                    dpd = max(0, (today - due_date).days)
                else:
                    paid_date = None
                    amount_paid = 0
                    status = "Overdue"
                    dpd = max(0, (today - due_date).days)

                simulated_installments.append((due_date, status))
            else:
                paid_date, amount_paid, status, dpd = None, 0, "Not Due", 0

            # The schedule row must be written (and, transitively, be safe
            # to flush) before any collection row references its
            # schedule_id - see CopyWriter.depends_on.
            sched_writer.add((
                this_sched_id, loan["loan_id"], inst_no, due_date, round(principal_remaining, 2),
                principal_due, interest_due, emi_due, closing_principal, amount_paid,
                paid_date, status, dpd,
            ))

            if inst_no <= installments_to_simulate and amount_paid > 0:
                collection_id += 1
                interest_component = min(amount_paid, interest_due)
                principal_component = round(amount_paid - interest_component, 2)
                penalty = round(min(50 + dpd * 2, 500), 2) if dpd > 0 else 0.0
                collected_by_employee_id = None
                collected_by_agent_id = None
                if random.random() < 0.5:
                    pool = employee_ids_by_branch.get(loan["branch_id"]) or []
                    if pool:
                        collected_by_employee_id = random.choice(pool)
                else:
                    pool = agent_ids_by_branch.get(loan["branch_id"]) or []
                    if pool:
                        collected_by_agent_id = random.choice(pool)
                coll_writer.add((
                    collection_id, f"RCP{collection_id:09d}", loan["loan_id"], this_sched_id,
                    loan["customer"].customer_id, paid_date, principal_component, interest_component,
                    penalty, round(amount_paid, 2), random.choice(PAYMENT_MODES),
                    collected_by_employee_id, collected_by_agent_id,
                ))

            principal_remaining = closing_principal
            due_date = (due_date.replace(day=1) + timedelta(days=32)).replace(day=min(loan["first_emi_date"].day, 28))

        # A loan's *current* delinquency is the unbroken run of unresolved
        # installments trailing at the end of its simulated life so far -
        # a later on-time/late payment is treated as the borrower catching
        # back up (collections applies it to clear the oldest arrear too),
        # not as ignoring history. Only an unbroken trailing streak still
        # open today keeps accruing DPD.
        current_dpd = 0
        if loan["loan_status"] == "Active":
            oldest_open_due_date = None
            for inst_due_date, inst_status in reversed(simulated_installments):
                if inst_status in ("Overdue", "Partially Paid"):
                    oldest_open_due_date = inst_due_date
                else:
                    break
            if oldest_open_due_date is not None and oldest_open_due_date < today:
                current_dpd = (today - oldest_open_due_date).days
        loan_final_dpd[loan["loan_id"]] = current_dpd
        loan_npa_flag[loan["loan_id"]] = current_dpd > 90

    sched_writer.flush()
    coll_writer.flush()
    log(f"repayment_schedule: {sched_writer.total} rows")
    log(f"collections: {coll_writer.total} rows")
    return loan_final_dpd, loan_npa_flag


def backfill_loan_dpd_and_npa(loan_final_dpd: dict, loan_npa_flag: dict, conn):
    log("Backfilling loans.current_dpd / npa_flag from simulated schedules...")
    rows = [(dpd, loan_npa_flag[lid], lid) for lid, dpd in loan_final_dpd.items()]
    with conn.cursor() as cur:
        psycopg2.extras.execute_batch(
            cur, "UPDATE loans SET current_dpd = %s, npa_flag = %s WHERE loan_id = %s", rows,
            page_size=5000,
        )
    conn.commit()


DPD_BUCKETS = [
    (0, 0, "Standard", "Standard", 0.0040),
    (1, 30, "SMA-0", "Standard", 0.0040),
    (31, 60, "SMA-1", "Standard", 0.0100),
    (61, 90, "SMA-2", "Standard", 0.1500),
    (91, 365, "NPA 91-365", "Sub-Standard", 0.2500),
    (366, 730, "NPA 1-2yr", "Doubtful", 0.5000),
    (731, 10_000, "NPA 2yr+", "Loss", 1.0000),
]


def bucket_for_dpd(dpd: int):
    for lo, hi, bucket, classification, prov in DPD_BUCKETS:
        if lo <= dpd <= hi:
            return bucket, classification, prov
    return DPD_BUCKETS[-1][2], DPD_BUCKETS[-1][3], DPD_BUCKETS[-1][4]


