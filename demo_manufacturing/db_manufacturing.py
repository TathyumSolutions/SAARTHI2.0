def generate_ledger(orders: list[ProdOrder], received_pos: list[dict], conn) -> None:
    writer = CopyWriter(conn, "transactions_ledger", [
        "transaction_id", "reference_number", "production_order_id", "customer_id",
        "transaction_type", "transaction_date", "amount", "payment_mode", "status",
    ])
    txn_id = 0
    for po in received_pos:
        txn_id += 1
        writer.add((
            txn_id, f"TXN{txn_id:010d}", None, None, "Raw Material Purchase",
            po["received_date"], po["total_amount"], "NEFT", "Success",
        ))
    for o in orders:
        txn_id += 1
        invoice_amount = round(o.quantity_ordered * o.unit_price, 2)
        writer.add((
            txn_id, f"TXN{txn_id:010d}", o.production_order_id, o.customer.customer_id,
            "Sales Invoice", o.order_date, invoice_amount, "Letter of Credit", "Success",
        ))
        if random.random() < 0.75:
            txn_id += 1
            payment_date = o.order_date + timedelta(days=random.randint(20, 90))
            writer.add((
                txn_id, f"TXN{txn_id:010d}", o.production_order_id, o.customer.customer_id,
                "Payment Received", min(payment_date, TODAY), invoice_amount,
                random.choice(PAYMENT_MODES), "Success",
            ))
    writer.flush()
    log(f"transactions_ledger: {writer.total} rows")


