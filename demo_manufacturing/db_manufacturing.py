def log(msg: str) -> None:
    print(f"[{datetime.now().strftime('%H:%M:%S')}] {msg}", flush=True)


def derive_db_url(base_url: str, db_name: str) -> str:
    parsed = urlparse(base_url)
    return parsed._replace(path=f"/{db_name}").geturl()


def gen_pan() -> str:
    letters1 = "".join(random.choices("ABCDEFGHIJKLMNOPQRSTUVWXYZ", k=5))
    digits = "".join(random.choices("0123456789", k=4))
    letter2 = random.choice("ABCDEFGHIJKLMNOPQRSTUVWXYZ")
    return f"{letters1}{digits}{letter2}"


def gen_gstin(state: str) -> str:
    state_code = GST_STATE_CODES.get(state, "27")
    pan = gen_pan()
    entity_code = random.choice("123456789")
    checksum = random.choice("0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ")
    return f"{state_code}{pan}{entity_code}Z{checksum}"


def gen_mobile() -> str:
    first = random.choice("6789")
    rest = "".join(random.choices("0123456789", k=9))
    return f"+91{first}{rest}"


def weighted_choice(pairs):
    values, weights = zip(*pairs)
    return random.choices(values, weights=weights, k=1)[0]


def random_date(start: date, end: date) -> date:
    delta_days = (end - start).days
    if delta_days <= 0:
        return start
    return start + timedelta(days=random.randint(0, delta_days))


def add_working_day(d: date) -> date:
    """Advance one calendar day, skipping Sundays (6-day work week)."""
    nd = d + timedelta(days=1)
    if nd.weekday() == 6:  # Sunday
        nd += timedelta(days=1)
    return nd


