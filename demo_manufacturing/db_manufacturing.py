# Reliability profile mix drives shop-floor disruption behaviour downstream.
RELIABILITY_PROFILES = [("Good", 0.60), ("Average", 0.30), ("Poor", 0.10)]
RELIABILITY_PARAMS = {
    "Good":    dict(p_disruption=0.03, p_recovery=0.60, reject_rate=0.010),
    "Average": dict(p_disruption=0.08, p_recovery=0.40, reject_rate=0.030),
    "Poor":    dict(p_disruption=0.16, p_recovery=0.22, reject_rate=0.070),
}
ORDER_ACCEPT_WEIGHTS = [("Accepted", 0.90), ("Rejected", 0.06), ("Cancelled", 0.04)]
REJECTION_REASONS = [
    "Customer credit limit exceeded", "Machine capacity unavailable in requested window",
    "Raw material lead time conflict", "Specification could not be met",
    "Customer over 90 days overdue on existing invoices",
]


@dataclass
class ProdOrder:
    production_order_id: int
    customer: Customer
    product: dict
    plant_id: int
    machine_id: int | None
    quantity_ordered: int
    unit_price: float
    order_date: date
    planned_start_date: date
    planned_end_date: date
    planned_days: int
    reliability_profile: str
    target_status: str  # Completed / In Progress / Delayed / On Hold


def generate_production_orders(
    customers: list[Customer], products: list[dict], plants: list[Plant],
    machine_ids_by_plant: dict, employee_ids_by_plant: dict,
    orders_per_customer: float, conn,
) -> tuple["CopyWriter", list[ProdOrder]]:
    writer = CopyWriter(conn, "production_orders", [
        "production_order_id", "order_number", "customer_id", "product_id", "plant_id",
        "machine_id", "supervisor_employee_id", "order_date", "quantity_ordered", "unit_price",
        "total_order_value", "planned_start_date", "planned_end_date", "actual_start_date",
        "actual_end_date", "quantity_produced", "quantity_rejected", "order_status", "priority",
        "reliability_profile", "delay_days", "at_risk_flag",
    ])
    order_id = 0
    active_orders: list[ProdOrder] = []

    for cust in customers:
        n_orders = np.random.poisson(orders_per_customer) or 1
        for _ in range(n_orders):
            order_id += 1
            product = random.choice(products)
            plant_id = cust.plant_id
            accept = weighted_choice(ORDER_ACCEPT_WEIGHTS)
            quantity_ordered = int(round(random.uniform(product["moq"], product["moq"] * 12)))
            unit_price = round(product["price"] * random.uniform(0.95, 1.1), 2)
            total_value = round(quantity_ordered * unit_price, 2)
            shift_capacity_per_day = max(1, round(8 * 60 / product["cycle_time"]))
            planned_days = max(2, min(120, -(-quantity_ordered // shift_capacity_per_day)))
            priority = weighted_choice([("Low", 0.20), ("Normal", 0.55), ("High", 0.20), ("Urgent", 0.05)])

            if accept != "Accepted":
                order_date = random_date(date(2019, 1, 1), TODAY - timedelta(days=5))
                writer.add((
                    order_id, f"PROD{order_id:08d}", cust.customer_id, product["product_id"], plant_id,
                    None, None, order_date, quantity_ordered, unit_price, total_value,
                    None, None, None, None, 0, 0,
                    accept, priority, weighted_choice(RELIABILITY_PROFILES), 0, False,
                ))
                continue

            target_status = weighted_choice([
                ("Completed", 0.58), ("In Progress", 0.18), ("Delayed", 0.12),
                ("On Hold", 0.07), ("Cancelled", 0.05),
            ])
            if target_status in ("In Progress", "Delayed", "On Hold"):
                order_date = random_date(TODAY - timedelta(days=150), TODAY - timedelta(days=15))
            else:
                order_date = random_date(date(2019, 1, 1), TODAY - timedelta(days=planned_days + 20))

            planned_start = order_date + timedelta(days=random.randint(2, 10))
            planned_end = planned_start + timedelta(days=planned_days)
            machine_pool = machine_ids_by_plant.get(plant_id) or []
            machine_id = random.choice(machine_pool) if machine_pool else None
            supervisor_pool = employee_ids_by_plant.get(plant_id) or []
            supervisor_id = random.choice(supervisor_pool) if supervisor_pool else None
            reliability_profile = weighted_choice(RELIABILITY_PROFILES)

            active_orders.append(ProdOrder(
                production_order_id=order_id, customer=cust, product=product, plant_id=plant_id,
                machine_id=machine_id, quantity_ordered=quantity_ordered, unit_price=unit_price,
                order_date=order_date, planned_start_date=planned_start, planned_end_date=planned_end,
                planned_days=planned_days, reliability_profile=reliability_profile,
                target_status=target_status if target_status != "Cancelled" else "Cancelled",
            ))

            if target_status == "Cancelled":
                writer.add((
                    order_id, f"PROD{order_id:08d}", cust.customer_id, product["product_id"], plant_id,
                    machine_id, supervisor_id, order_date, quantity_ordered, unit_price, total_value,
                    planned_start, planned_end, None, None, 0, 0,
                    "Cancelled", priority, reliability_profile, 0, False,
                ))
                active_orders.pop()  # cancelled orders don't get a production_log simulation
                continue

            # Placeholder row - quantity_produced/quantity_rejected/order_status/delay_days/
            # at_risk_flag/actual_start_date/actual_end_date are finalized after the
            # production_log simulation (UPDATE pass), mirroring how a loan's DPD/NPA
            # flag is only known once its repayment schedule has been simulated.
            writer.add((
                order_id, f"PROD{order_id:08d}", cust.customer_id, product["product_id"], plant_id,
                machine_id, supervisor_id, order_date, quantity_ordered, unit_price, total_value,
                planned_start, planned_end, None, None, 0, 0,
                "In Progress", priority, reliability_profile, 0, False,
            ))

    writer.flush()
    log(f"production_orders: {writer.total} rows")
    return writer, active_orders


def simulate_and_write_production_log(
    orders: list[ProdOrder], employee_ids_by_plant: dict, machine_ids_by_plant: dict, conn,
):
    writer = CopyWriter(conn, "production_log", [
        "log_id", "production_order_id", "log_date", "shift", "planned_qty", "produced_qty",
        "rejected_qty", "machine_id", "operator_employee_id", "downtime_minutes", "log_status",
    ])

    log_id = 0
    results: dict[int, dict] = {}

    for o in orders:
        params = RELIABILITY_PARAMS[o.reliability_profile]
        daily_planned_qty = max(1, round(o.quantity_ordered / o.planned_days))

        if o.target_status == "Completed":
            days_to_simulate = o.planned_days + (random.randint(0, 15) if random.random() < 0.25 else 0)
        else:
            elapsed = (TODAY - o.planned_start_date).days
            days_to_simulate = max(1, min(elapsed, o.planned_days * 3))

        disrupted = False
        produced_total = 0
        rejected_total = 0
        cur_day = o.planned_start_date
        day_statuses: list[str] = []
        employee_pool = employee_ids_by_plant.get(o.plant_id) or []
        machine_pool = machine_ids_by_plant.get(o.plant_id) or ([o.machine_id] if o.machine_id else [])

        for _day_num in range(days_to_simulate):
            if produced_total >= o.quantity_ordered:
                break
            remaining = o.quantity_ordered - produced_total
            planned_qty = min(daily_planned_qty, remaining)

            just_disrupted = False
            if not disrupted and random.random() < params["p_disruption"]:
                disrupted = True
                just_disrupted = True

            if not disrupted:
                produced_qty = round(planned_qty * random.uniform(0.90, 1.05))
                downtime = random.randint(0, 45)
                status = "On Track"
            elif (not just_disrupted) and random.random() < params["p_recovery"]:
                disrupted = False
                produced_qty = round(planned_qty * random.uniform(0.55, 0.90))
                downtime = random.randint(60, 180)
                status = "Delayed"
            else:
                produced_qty = round(planned_qty * random.uniform(0.0, 0.35))
                downtime = random.randint(150, 420)
                status = "Stopped" if produced_qty == 0 else "Delayed"

            produced_qty = min(produced_qty, remaining)
            rejected_qty = round(produced_qty * params["reject_rate"] * random.uniform(0.5, 1.6))
            produced_total += produced_qty
            rejected_total += rejected_qty
            day_statuses.append(status)

            log_id += 1
            writer.add((
                log_id, o.production_order_id, cur_day,
                random.choice(["Morning", "Afternoon", "Night"]),
                planned_qty, produced_qty, rejected_qty,
                random.choice(machine_pool) if machine_pool else None,
                random.choice(employee_pool) if employee_pool else None,
                downtime, status,
            ))
            cur_day = add_working_day(cur_day)

        # A production order's *current* delay is the unbroken run of
        # Delayed/Stopped days trailing at the end of its simulated life so
        # far - a later on-track day is the shop floor catching back up, not
        # ignoring history. Only used for orders still open (not Completed).
        delay_days = 0
        if o.target_status != "Completed":
            trailing_bad_days = 0
            for status in reversed(day_statuses):
                if status in ("Delayed", "Stopped"):
                    trailing_bad_days += 1
                else:
                    break
            delay_days = trailing_bad_days

        quantity_produced = min(produced_total, o.quantity_ordered)
        completed = o.target_status == "Completed" or quantity_produced >= o.quantity_ordered
        if completed:
            final_status = "Completed"
            actual_end = cur_day
        elif o.target_status == "On Hold":
            final_status = "On Hold"
            actual_end = None
        else:
            final_status = "Delayed" if delay_days > 5 else "In Progress"
            actual_end = None

        results[o.production_order_id] = dict(
            quantity_produced=quantity_produced,
            quantity_rejected=rejected_total,
            order_status=final_status,
            delay_days=delay_days,
            at_risk_flag=delay_days > 10 or (final_status == "Delayed" and delay_days > 5),
            actual_start_date=o.planned_start_date,
            actual_end_date=actual_end,
        )

    writer.flush()
    log(f"production_log: {writer.total} rows")
    return results


def backfill_production_orders(results: dict[int, dict], conn) -> None:
    log("Backfilling production_orders from simulated production_log...")
    rows = [
        (r["quantity_produced"], r["quantity_rejected"], r["order_status"], r["delay_days"],
         r["at_risk_flag"], r["actual_start_date"], r["actual_end_date"], pid)
        for pid, r in results.items()
    ]
    with conn.cursor() as cur:
        psycopg2.extras.execute_batch(
            cur,
            """UPDATE production_orders
               SET quantity_produced = %s, quantity_rejected = %s, order_status = %s,
                   delay_days = %s, at_risk_flag = %s, actual_start_date = %s, actual_end_date = %s
               WHERE production_order_id = %s""",
            rows, page_size=5000,
        )
    conn.commit()


def generate_shipments(
    orders: list[ProdOrder], results: dict[int, dict], employee_ids_by_plant: dict, conn,
) -> None:
    writer = CopyWriter(conn, "shipments", [
        "shipment_id", "shipment_number", "production_order_id", "customer_id", "plant_id",
        "shipment_date", "quantity_shipped", "unit_price", "freight_amount", "total_invoice_amount",
        "transporter", "transport_mode", "shipment_status", "delivered_date", "dispatched_by_employee_id",
    ])
    shipment_id = 0
    for o in orders:
        res = results.get(o.production_order_id)
        if not res or res["quantity_produced"] <= 0:
            continue
        n_shipments = 1 if res["quantity_produced"] < o.product["moq"] * 2 else random.randint(1, 3)
        qty_left = res["quantity_produced"]
        base_date = res["actual_start_date"] or o.planned_start_date
        pool = employee_ids_by_plant.get(o.plant_id) or []
        for i in range(n_shipments):
            if qty_left <= 0:
                break
            qty = qty_left if i == n_shipments - 1 else round(qty_left / (n_shipments - i) * random.uniform(0.8, 1.2))
            qty = max(1, min(qty, qty_left))
            qty_left -= qty
            shipment_id += 1
            ship_date = min(base_date + timedelta(days=random.randint(3, 30) * (i + 1)), TODAY)
            freight = round(qty * random.uniform(0.5, 3.0), 2)
            invoice_amount = round(qty * o.unit_price + freight, 2)
            mode = weighted_choice(TRANSPORT_MODES)
            status = weighted_choice([("Delivered", 0.80), ("In Transit", 0.12),
                                       ("Dispatched", 0.06), ("Returned", 0.02)])
            delivered = ship_date + timedelta(days=random.randint(1, 10)) if status == "Delivered" else None
            if delivered and delivered > TODAY:
                delivered = TODAY
            writer.add((
                shipment_id, f"SHP{shipment_id:08d}", o.production_order_id, o.customer.customer_id,
                o.plant_id, ship_date, int(qty), o.unit_price, freight, invoice_amount,
                random.choice(TRANSPORTERS), mode, status, delivered,
                random.choice(pool) if pool else None,
            ))
    writer.flush()
    log(f"shipments: {writer.total} rows")


DOWNTIME_CATEGORIES = [
    ("Scheduled Maintenance", 0.55, "Low"),
    ("Minor Breakdown", 0.28, "Medium"),
    ("Major Breakdown", 0.12, "High"),
    ("Extended Outage", 0.05, "Critical"),
]


def generate_machine_downtime(machines: list[Machine], conn) -> None:
    writer = CopyWriter(conn, "machine_downtime", [
        "downtime_id", "machine_id", "as_of_date", "downtime_category", "downtime_hours",
        "maintenance_cost", "criticality",
    ])
    downtime_id = 0
    for m in machines:
        n_events = np.random.poisson(2.0)
        for _ in range(n_events):
            category, _, criticality = weighted_choice(
                [((c, w, cr), w) for c, w, cr in DOWNTIME_CATEGORIES]
            )
            hours = {
                "Scheduled Maintenance": random.uniform(2, 12),
                "Minor Breakdown": random.uniform(1, 8),
                "Major Breakdown": random.uniform(8, 48),
                "Extended Outage": random.uniform(48, 200),
            }[category]
            cost = round(hours * random.uniform(500, 3500), 2)
            as_of = random_date(date(2023, 1, 1), TODAY)
            downtime_id += 1
            writer.add((downtime_id, m.machine_id, as_of, category, round(hours, 2), cost, criticality))
    writer.flush()
    log(f"machine_downtime: {writer.total} rows")


INSPECTION_STAGES = ["Incoming Material", "In-Process", "Final Inspection", "Customer Return"]


def generate_quality_inspection_records(orders: list[ProdOrder], employee_ids_by_plant: dict, conn) -> None:
    writer = CopyWriter(conn, "quality_inspection_records", [
        "inspection_id", "production_order_id", "product_id", "inspection_date",
        "inspector_employee_id", "inspection_stage", "sample_size", "defects_found",
        "defect_rate_pct", "result",
    ])
    inspection_id = 0
    base_defect_rate = {"Good": 0.01, "Average": 0.03, "Poor": 0.08}
    for o in orders:
        pool = employee_ids_by_plant.get(o.plant_id) or []
        n_inspections = random.randint(1, 3)
        stages = random.sample(INSPECTION_STAGES[:3], k=min(n_inspections, 3))
        for stage in stages:
            sample_size = random.randint(10, 200)
            rate = max(0.0, np.random.normal(base_defect_rate[o.reliability_profile], 0.02))
            defects = min(sample_size, round(sample_size * rate))
            defect_rate_pct = round(100 * defects / sample_size, 2)
            result = "Pass" if defect_rate_pct < 2.0 else ("Rework" if defect_rate_pct < 6.0 else "Fail")
            inspection_id += 1
            inspection_date = min(o.planned_start_date + timedelta(days=random.randint(1, o.planned_days + 5)), TODAY)
            writer.add((
                inspection_id, o.production_order_id, o.product["product_id"], inspection_date,
                random.choice(pool) if pool else None, stage, sample_size, int(defects),
                defect_rate_pct, result,
            ))
    writer.flush()
    log(f"quality_inspection_records: {writer.total} rows")


