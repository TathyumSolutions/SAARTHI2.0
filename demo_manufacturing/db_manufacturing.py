"""
db_manufacturing.py
====================
Generates a realistic, synthetic manufacturing-company database (raw
material procurement -> shop-floor production -> quality inspection ->
dispatch/shipment -> payables -> machine downtime -> ledger) with Indian
supplier/customer data, for use as a demo/test data source inside Saarthi.

This is a self-contained companion project (data + a stub validation API +
Excel reference tables + factory policy docs live under
demo_manufacturing/) - it does not touch the main Saarthi Flask app's
models or logical databases; it provisions its own Postgres database and
can be registered as one more "database connection" data source inside
Saarthi once loaded.

ALL DATA IS SYNTHETIC. Names/companies are generated by Faker's en_IN
locale; GSTIN, mobile numbers, invoice numbers etc. are randomly generated
in the right *format* and are not real identifiers.

Usage
-----
    python db_manufacturing.py --scale small   # quick smoke test
    python db_manufacturing.py --scale medium
    python db_manufacturing.py --scale full     # default

    python db_manufacturing.py --scale full --db-url postgresql://user:pass@host:5432/postgres

Environment variables (used when --db-url is not given):
    MANUFACTURING_DATABASE_URL   base Postgres URL (server + credentials
                                  only; the database name itself is always
                                  "manufacturing_demo_db", created if missing)
                                  default: postgresql://saarthi:password@localhost:5432/postgres
"""

