def ensure_database(base_url: str, db_name: str) -> None:
    parsed = urlparse(base_url)
    maint_conn = psycopg2.connect(
        dbname="postgres", user=parsed.username, password=parsed.password,
        host=parsed.hostname, port=parsed.port or 5432,
    )
    maint_conn.set_isolation_level(ISOLATION_LEVEL_AUTOCOMMIT)
    try:
        with maint_conn.cursor() as cur:
            cur.execute("SELECT 1 FROM pg_database WHERE datname = %s", (db_name,))
            if not cur.fetchone():
                log(f"Creating database '{db_name}'...")
                cur.execute(f'CREATE DATABASE "{db_name}"')
            else:
                log(f"Database '{db_name}' already exists - will be reset (schema DROP/CREATE).")
    finally:
        maint_conn.close()


class CopyWriter:
    """Buffers rows for one table and flushes them via COPY in batches."""

    def __init__(self, conn, table: str, columns: list[str], depends_on: list["CopyWriter"] | None = None):
        self.conn = conn
        self.table = table
        self.columns = columns
        self.buffer = io.StringIO()
        self.count_in_buffer = 0
        self.total = 0
        # Writers for tables this one holds foreign keys into. Flushed
        # before this writer's own buffer so a row can never reference an
        # id that hasn't actually been COPY'd (and committed) yet.
        self.depends_on = depends_on or []

    @staticmethod
    def _fmt(value) -> str:
        if value is None:
            return r"\N"
        if isinstance(value, bool):
            return "t" if value else "f"
        if isinstance(value, (date, datetime)):
            return value.isoformat()
        if isinstance(value, str):
            return value.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n").replace("\r", "")
        return str(value)

    def add(self, row: tuple) -> None:
        self.buffer.write("\t".join(self._fmt(v) for v in row))
        self.buffer.write("\n")
        self.count_in_buffer += 1
        if self.count_in_buffer >= COPY_BATCH_ROWS:
            self.flush()

    def flush(self) -> None:
        for dep in self.depends_on:
            dep.flush()
        if self.count_in_buffer == 0:
            return
        self.buffer.seek(0)
        with self.conn.cursor() as cur:
            cur.copy_expert(
                f"COPY {self.table} ({', '.join(self.columns)}) FROM STDIN WITH (FORMAT text)",
                self.buffer,
            )
        self.conn.commit()
        self.total += self.count_in_buffer
        self.buffer = io.StringIO()
        self.count_in_buffer = 0


